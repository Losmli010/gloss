//! gloss-core 测试桩库：端口替身与脚本引擎的唯一存放处。
//!
//! 按被替身的对象分文件：引擎桩（引擎端口的脚本桩）、
//! 端口桩（其余端口替身）。供两类编译上下文共享同一份源：
//! - 集成测试目标（各测试文件引入桩模块）；
//! - 源码内联单测（以测试属性并入为桩模块）。
//!
//! 因此本模块统一以核心库的绝对路径引用库条目（库入口
//! 以自身名字重导出让自引用成立）。本模块按生产代码
//! 对待（注释规则同源码目录，见 AGENTS.md「注释纪律」）。
//!
//! 桩只承担两件事：**预置返回值**与**可注入的失败**——注入点要能造出想测
//! 的那种时序，观测点要能证明它发生过（见 AGENTS.md「测试」一节）。需要
//! 新能力时扩展本模块，别在测试里手搓替身。桩按包自持：跨包
//! 刻意不共享（各包的测试桩目录各留所需副本），一份桩的行为变化
//! 不得静默改写另一个包测试套件的语义。

#![allow(dead_code)]

use std::sync::{Mutex, MutexGuard, PoisonError};

pub mod engine;
pub mod ports;

fn lock_or_recover<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
    mutex.lock().unwrap_or_else(PoisonError::into_inner)
}
