//! 共享测试桩库（单一事实源，源文件住核心库）：引擎桩（引擎端口的脚本桩）
//! 与端口桩（配置存储/密钥存储替身）全仓唯一，按被替身的对象分文件。
//!
//! 供三类编译上下文共享同一份源：
//! - 核心库的集成测试目标与源码内联单测；
//! - 下游包的测试（应用层、传输分包）以路径属性并入同一份源（K5 定案的
//!   单源消费，验收单点是核心库的桩行为测试）。
//!
//! 因此本模块统一以核心库的绝对路径引用库条目（库入口
//! 以自身名字重导出让自引用成立，跨包并入时解析到真实依赖）。
//! 本模块按生产代码对待（注释规则同源码目录）。
//!
//! 桩只承担两件事：“预置返回值”与“可注入的失败”——注入点要能造出想测
//! 的那种时序，观测点要能证明它发生过。需要
//! 新能力时扩展本模块，别在测试里手搓替身。包专属桩（探针、平台替身）
//! 仍各包自持，不进本目录。

#![allow(dead_code)]

use std::sync::{Mutex, MutexGuard, PoisonError};

pub mod engine;
pub mod ports;

fn lock_or_recover<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
    mutex.lock().unwrap_or_else(PoisonError::into_inner)
}
